#!/usr/bin/env python3
"""
Turns AJ's profile artwork in ./Profile into web-sized copies for the intro.

    python3 scripts/profile-art.py

Reads ./Profile (never modified), writes AVIF + WebP files to ./public/intro
and regenerates src/data/introArt.ts — the manifest the intro reads.
Metadata is not carried over.

Images are recognised by what they show, not by their filenames:
  * shape  — the portraits are roughly square, the chess lineups are wide;
  * colour — the light in the "red" images is strongly red, the "white"
    images are neutral.
Anything that doesn't fit is reported and skipped.

The two chess lineups are joined into one: white king, queen and knight on
the left, red rook, bishop, pawn and signature on the right, meeting in the
gap between knight and rook. Both lineups put that gap in the same place;
the red one sits 28px lower, so it is raised to make the neon line run on
unbroken from white into red.

Requires Pillow 11+ (for AVIF):  pip install pillow
"""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Profile"
OUT = ROOT / "public" / "intro"
MANIFEST = ROOT / "src" / "data" / "introArt.ts"

IMAGE_TYPES = {".jpg", ".jpeg", ".png", ".webp", ".avif"}
PORTRAIT_WIDTHS = (640, 960, 1312)
CHESS_WIDTHS = (900, 1400, 1800)

# The lineups, in source pixels (both are 2055 x 765), measured from the art.
CHESS_SEAM_X = 958          # the gap between the knight and the rook
CHESS_RED_RAISE = 28        # red line sits this much lower at the seam
CHESS_CROP = (150, 170, 1950, 620)   # left, top, right, bottom — pieces, line, reflections
CHESS_FEATHER = 28          # crossfade width at the seam


def classify(im: Image.Image) -> tuple[str, str] | None:
    """('portrait' | 'chess', 'white' | 'red') from shape and light colour."""
    w, h = im.size
    ratio = w / h
    kind = "portrait" if 0.8 < ratio < 1.4 else "chess" if ratio > 2.2 else None
    if not kind:
        return None
    # Count rim-light pixels: saturated red versus near-white. (An average
    # colour would be pulled towards red by skin tones.)
    raw = im.resize((w // 8, h // 8)).tobytes()
    px = [raw[i : i + 3] for i in range(0, len(raw), 3)]
    red = sum(1 for r, g, b in px if r > 150 and g < 110 and b < 110)
    white = sum(1 for r, g, b in px if min(r, g, b) > 185)
    tone = "red" if red > 4 * white and red > 100 else "white" if white > red else None
    return (kind, tone) if tone else None


def join_chess(white: Image.Image, red: Image.Image) -> Image.Image:
    left, top, right, bottom = CHESS_CROP
    w_part = white.crop((left, top, right, bottom))
    r_part = red.crop((left, top + CHESS_RED_RAISE, right, bottom + CHESS_RED_RAISE))
    seam = CHESS_SEAM_X - left
    mask = Image.new("L", w_part.size, 0)
    for x in range(w_part.width):
        t = (x - (seam - CHESS_FEATHER / 2)) / CHESS_FEATHER
        mask.paste(round(255 * min(1, max(0, t))), (x, 0, x + 1, w_part.height))
    return Image.composite(r_part, w_part, mask)


def save(im: Image.Image, name: str, widths: tuple[int, ...]) -> list[int]:
    w, h = im.size
    # Never upscale: the largest copy is at most the source width.
    out = sorted({x for x in widths if x < w} | {min(w, widths[-1])})
    for width in out:
        frame = im if width == w else im.resize((width, round(h * width / w)), Image.LANCZOS)
        frame.save(OUT / f"{name}-{width}.avif", quality=56, speed=4)
        frame.save(OUT / f"{name}-{width}.webp", quality=82, method=6)
    return out


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    found: dict[tuple[str, str], Image.Image] = {}
    for f in sorted(SRC.iterdir()):
        if f.suffix.lower() not in IMAGE_TYPES:
            continue
        with Image.open(f) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
        key = classify(im)
        if not key or key in found:
            print(f"skipped ({'duplicate ' + '/'.join(key) if key else 'not recognised'}): {f.name}")
            continue
        found[key] = im
        print(f"{f.name} -> {key[1]} {key[0]}")

    entries = []
    for tone in ("white", "red"):
        im = found.get(("portrait", tone))
        if im:
            entries.append((tone, save(im, tone, PORTRAIT_WIDTHS), im.size))
    if ("chess", "white") in found and ("chess", "red") in found:
        chess = join_chess(found[("chess", "white")], found[("chess", "red")])
        entries.append(("chess", save(chess, "chess", CHESS_WIDTHS), chess.size))
        seam = (CHESS_SEAM_X - CHESS_CROP[0]) / chess.width

    lines = [
        "// Generated by scripts/profile-art.py — do not edit by hand.",
        "// Lists the web-sized intro artwork in public/intro.",
        "",
        "export interface IntroArt {",
        "  /** Available widths, ascending; files are intro/<id>-<width>.(avif|webp). */",
        "  widths: number[];",
        "  /** Source aspect ratio as width / height. */",
        "  ratio: number;",
        "}",
        "",
        "export const INTRO_ART: Record<string, IntroArt> = {",
    ]
    for name, widths, (w, h) in entries:
        lines.append(f"  {name}: {{ widths: [{', '.join(map(str, widths))}], ratio: {w / h:.4f} }},")
    lines += ["};", ""]
    if any(e[0] == "chess" for e in entries):
        lines += ["/** Where white meets red in the joined chess lineup, as a fraction of its width. */",
                  f"export const CHESS_SEAM = {seam:.4f};", ""]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
