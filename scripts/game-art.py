#!/usr/bin/env python3
"""
Turns the original game artwork in ./Games into web-sized copies.

    python3 scripts/game-art.py

Reads ./Games (never modified), writes resized AVIF + WebP files to
./public/games and regenerates src/data/gameArt.ts — the manifest the Games
chapter reads. Metadata (EXIF etc.) is not carried over.

To add a game's artwork: drop the image in ./Games, add a line to SOURCES
below mapping the file to the game's id in src/data/worlds.ts, and run the
script again. Files that are not listed are reported and skipped, so an
image is never assigned to a game by guessing from its filename.

Requires Pillow 11+ (for AVIF):  pip install pillow
"""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Games"
OUT = ROOT / "public" / "games"
MANIFEST = ROOT / "src" / "data" / "gameArt.ts"

# file in ./Games  ->  game id in src/data/worlds.ts   (checked by eye)
SOURCES = {
    "monster-hunter-world_eyst.jpg": "monster-hunter-world",
    "elden-ring-2022-games-pc-games-playstation-4-xbox-series-x-3840x2160-7474.jpg": "elden-ring",
    "sekiro-no-defeat-8k-3840x2160-26113.jpg": "sekiro",
    "god-of-war-ragnarok-kratos-freya-atreus-2022-games-3840x2160-8677.jpg": "god-of-war",
    "black-myth-wukong-3840x2160-17948.jpeg": "black-myth-wukong",
}

WIDTHS = (640, 1280, 1920)
IMAGE_TYPES = {".jpg", ".jpeg", ".png", ".webp", ".avif"}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    entries = []
    for f in sorted(SRC.iterdir()):
        if f.suffix.lower() not in IMAGE_TYPES:
            continue
        gid = SOURCES.get(f.name)
        if not gid:
            print(f"skipped (not mapped in SOURCES): {f.name}")
            continue
        with Image.open(f) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            w, h = im.size
            # Never upscale: a small source gets one copy at its own width.
            widths = [x for x in WIDTHS if x < w] + [min(w, WIDTHS[-1])]
            widths = sorted(set(widths))
            for width in widths:
                height = round(h * width / w)
                frame = im if width == w else im.resize((width, height), Image.LANCZOS)
                frame.save(OUT / f"{gid}-{width}.avif", quality=52, speed=4)
                frame.save(OUT / f"{gid}-{width}.webp", quality=80, method=6)
            entries.append((gid, widths, w, h))
            print(f"{f.name} -> {gid} {widths}")

    lines = [
        "// Generated by scripts/game-art.py — do not edit by hand.",
        "// Lists the web-sized artwork in public/games for each game id.",
        "",
        "export interface GameArt {",
        "  /** Available widths, ascending; files are games/<id>-<width>.(avif|webp). */",
        "  widths: number[];",
        "  /** Source aspect ratio as width / height. */",
        "  ratio: number;",
        "}",
        "",
        "export const GAME_ART: Record<string, GameArt> = {",
    ]
    for gid, widths, w, h in entries:
        lines.append(f"  '{gid}': {{ widths: [{', '.join(map(str, widths))}], ratio: {w / h:.4f} }},")
    lines += ["};", ""]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
