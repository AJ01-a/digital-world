#!/usr/bin/env python3
"""
Turns the book photo in ./Books into a web-sized, straightened cover.

    python3 scripts/book-art.py

Reads ./Books (never modified), writes AVIF + WebP copies of the cover to
./public/books and regenerates src/data/bookArt.ts — the manifest the book
chapter reads. Metadata (EXIF etc.) is not carried over.

The source is a styled flat-lay photo with the book in the middle, so each
entry in SOURCES names the four corners of the cover in the original (found
by eye and checked against the pixels). The script cuts the cover out along
those corners and straightens it, so the page can light and frame it itself.
Files that are not listed are reported and skipped.

Requires Pillow 11+ (for AVIF):  pip install pillow
"""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Books"
OUT = ROOT / "public" / "books"
MANIFEST = ROOT / "src" / "data" / "bookArt.ts"

# file in ./Books -> (artwork id, cover corners: top-left, bottom-left, bottom-right, top-right)
SOURCES = {
    "atomic-habits_gallery_hi-res_01.jpg": (
        "atomic-habits",
        ((693, 254), (687, 890), (1120, 891), (1111, 252)),
    ),
}

WIDTHS = (320, 480)
IMAGE_TYPES = {".jpg", ".jpeg", ".png", ".webp", ".avif"}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    entries = []
    for f in sorted(SRC.iterdir()):
        if f.suffix.lower() not in IMAGE_TYPES:
            continue
        source = SOURCES.get(f.name)
        if not source:
            print(f"skipped (not mapped in SOURCES): {f.name}")
            continue
        aid, (tl, bl, br, tr) = source
        with Image.open(f) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            # The cover's own size in the photo, so nothing is upscaled.
            w = round(((tr[0] - tl[0]) + (br[0] - bl[0])) / 2)
            h = round(((bl[1] - tl[1]) + (br[1] - tr[1])) / 2)
            cover = im.transform((w, h), Image.QUAD, (*tl, *bl, *br, *tr), Image.BICUBIC)
            widths = sorted({x for x in WIDTHS if x < w} | {min(w, WIDTHS[-1])})
            for width in widths:
                height = round(h * width / w)
                frame = cover if width == w else cover.resize((width, height), Image.LANCZOS)
                frame.save(OUT / f"{aid}-{width}.avif", quality=64, speed=4)
                frame.save(OUT / f"{aid}-{width}.webp", quality=86, method=6)
            entries.append((aid, widths, w, h))
            print(f"{f.name} -> {aid} {widths} ({w}x{h})")

    lines = [
        "// Generated by scripts/book-art.py — do not edit by hand.",
        "// Lists the web-sized covers in public/books for each artwork id.",
        "",
        "export interface BookArt {",
        "  /** Available widths, ascending; files are books/<id>-<width>.(avif|webp). */",
        "  widths: number[];",
        "  /** Cover aspect ratio as width / height. */",
        "  ratio: number;",
        "}",
        "",
        "export const BOOK_ART: Record<string, BookArt> = {",
    ]
    for aid, widths, w, h in sorted(entries):
        lines.append(f"  '{aid}': {{ widths: [{', '.join(map(str, widths))}], ratio: {w / h:.4f} }},")
    lines += ["};", ""]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
