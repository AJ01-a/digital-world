#!/usr/bin/env python3
"""
Turns the original show artwork in ./Shows into web-sized copies.

    python3 scripts/show-art.py

Reads ./Shows (never modified), writes resized AVIF + WebP files to
./public/shows and regenerates src/data/showArt.ts — the manifest the One
Piece and Loki chapters read. Metadata (EXIF etc.) is not carried over.

Works exactly like scripts/game-art.py: map each file to an artwork id in
SOURCES below and run the script again. Files that are not listed are
reported and skipped, so an image is never assigned by filename guesswork.

Requires Pillow 11+ (for AVIF):  pip install pillow
"""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Shows"
OUT = ROOT / "public" / "shows"
MANIFEST = ROOT / "src" / "data" / "showArt.ts"

# file in ./Shows  ->  artwork id used by the chapters   (checked by eye)
SOURCES = {
    "laughing-luffy-one-3840x2160-19342.jpg": "luffy-gear-5",
    "monkey-d-luffy-hat-3840x2160-18701.png": "straw-hat",
    "loki-2023-series-3840x2160-12514.jpg": "loki-tva",
    "tom-hiddleston-loki-3840x2160-13479.jpg": "loki-throne",
}

WIDTHS = (640, 1280, 1920)
IMAGE_TYPES = {".jpg", ".jpeg", ".png", ".webp", ".avif"}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    entries = []
    for f in sorted(SRC.iterdir()):
        if f.suffix.lower() not in IMAGE_TYPES:
            continue
        aid = SOURCES.get(f.name)
        if not aid:
            print(f"skipped (not mapped in SOURCES): {f.name}")
            continue
        with Image.open(f) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            w, h = im.size
            # Never upscale: a small source gets one copy at its own width.
            widths = sorted({x for x in WIDTHS if x < w} | {min(w, WIDTHS[-1])})
            for width in widths:
                height = round(h * width / w)
                frame = im if width == w else im.resize((width, height), Image.LANCZOS)
                frame.save(OUT / f"{aid}-{width}.avif", quality=52, speed=4)
                frame.save(OUT / f"{aid}-{width}.webp", quality=80, method=6)
            entries.append((aid, widths, w, h))
            print(f"{f.name} -> {aid} {widths}")

    lines = [
        "// Generated by scripts/show-art.py — do not edit by hand.",
        "// Lists the web-sized artwork in public/shows for each artwork id.",
        "",
        "export interface ShowArt {",
        "  /** Available widths, ascending; files are shows/<id>-<width>.(avif|webp). */",
        "  widths: number[];",
        "  /** Source aspect ratio as width / height. */",
        "  ratio: number;",
        "}",
        "",
        "export const SHOW_ART: Record<string, ShowArt> = {",
    ]
    for aid, widths, w, h in sorted(entries):
        lines.append(f"  '{aid}': {{ widths: [{', '.join(map(str, widths))}], ratio: {w / h:.4f} }},")
    lines += ["};", ""]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
